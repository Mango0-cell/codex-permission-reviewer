import { chmod, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';

// Preserve installed paths without keeping a second handwritten JavaScript
// implementation. npm prepare produces these alongside the compiled runtime.
const root = fileURLToPath(new URL('../../', import.meta.url));
const generated = '// Generated by the TypeScript build; do not edit.\n';
const launchers: Record<string, string> = {
  'bin/cli.mjs': '#!/usr/bin/env node\n' + generated + 'import "../dist/bin/cli.js";\n',
  'scripts/app-server-client.mjs': generated + 'export * from "../dist/scripts/app-server-client.js";\n',
  'scripts/server.mjs': '#!/usr/bin/env node\n' + generated + [
    'import { resolve } from "node:path";',
    'import { pathToFileURL } from "node:url";',
    'import { main } from "../dist/src/transport/mcp.js";',
    'export * from "../dist/scripts/server.js";',
    'if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {',
    '  main().catch(() => { process.exitCode = 1; });',
    '}',
    '',
  ].join('\n'),
};
for (const directory of ['bin', 'scripts']) await mkdir(join(root, directory), { recursive: true });
for (const [path, content] of Object.entries(launchers)) {
  await writeFile(join(root, path), content, 'utf8');
  await chmod(join(root, path), 0o755);
}
